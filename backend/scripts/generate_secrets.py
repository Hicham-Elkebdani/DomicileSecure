"""Print fresh secrets to paste into backend/.env (never commit them).

python scripts/generate_secrets.py
"""

from __future__ import annotations

import base64
import secrets

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec


def vapid_keys() -> tuple[str, str]:
    """Web Push (VAPID) key pair, in the base64url formats expected by browsers/pywebpush."""
    private_key = ec.generate_private_key(ec.SECP256R1())
    private_value = private_key.private_numbers().private_value.to_bytes(32, "big")
    public_bytes = private_key.public_key().public_bytes(
        serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint
    )

    def b64(data: bytes) -> str:
        return base64.urlsafe_b64encode(data).rstrip(b"=").decode()

    return b64(public_bytes), b64(private_value)


def main() -> None:
    public, private = vapid_keys()
    print("# --- generated by scripts/generate_secrets.py ---")
    print(f"JWT_SECRET_KEY={secrets.token_urlsafe(48)}")
    print(f"WORKER_API_KEY={secrets.token_urlsafe(32)}")
    print(f"VAPID_PUBLIC_KEY={public}")
    print(f"VAPID_PRIVATE_KEY={private}")


if __name__ == "__main__":
    main()
